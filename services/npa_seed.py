def npa_hay_match(query: str, hay: str) -> bool:
    """Токенное сопоставление с учётом словоформ.

    Каждый токен запроса должен совпасть с каким-либо словом в hay:
      — токен из цифр/неё (длина < 3): точное вхождение подстроки;
      — иначе: общий префикс длиной max(3, len-2) символов.
    Пример: 'специальная оценка' найдёт 'специальной оценке'.
    """
    q = (query or "").strip().lower()
    if not q:
        return True
    hay_l = hay.lower()
    words = hay_l.split()
    for tok in q.split():
        if len(tok) < 3 or tok.isdigit():
            if tok not in hay_l:
                return False
            continue
        need = max(3, len(tok) - 2)
        if not any(w.startswith(tok[:need]) for w in words):
            return False
    return True


def seed_npa(db) -> int:
    """Заполнить каталог НПА, если он пуст. Возвращает число добавленных."""
    try:
        rows = db.fetch_all("SELECT COUNT(*) AS c FROM npa_documents")
        if rows and rows[0]["c"] > 0:
            return 0
        n = 0
        for (
            kind,
            number,
            title,
            date,
            status,
            category,
            audience,
            url,
            notes,
        ) in NPA_SEED:
            db._backend.execute(
                "INSERT INTO npa_documents "
                "(kind, number, title, date, status, category, audience, url, notes) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
                (kind, number, title, date, status, category, audience, url, notes),
            )
            n += 1
        db._backend.commit()
        return n
    except Exception:
        db._backend.rollback()
        return 0
